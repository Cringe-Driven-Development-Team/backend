-- Standalone primary only: Find discovers the sid from the refresh index.
-- Versions and user IDs always remain decimal strings, never Lua numbers.
local op = ARGV[1]
local input = cjson.decode(ARGV[2])
local prefix = ARGV[3]
local clock = redis.call('TIME')
local now = tonumber(clock[1]) * 1000 + math.floor(tonumber(clock[2]) / 1000)
local function decimal(v)
    return type(v) == 'string' and string.match(v, '^[1-9][0-9]*$') and
        (#v < 20 or (#v == 20 and v <= '18446744073709551615'))
end
local function version(key)
    local v = redis.call('GET', key)
    if v and not decimal(v) then error('corrupt session version') end
    return v
end
local function read(key)
    local raw = redis.call('GET', key)
    if not raw then return nil end
    local v = cjson.decode(raw)
    if type(v) ~= 'table' or type(v.sid) ~= 'string' or v.sid == '' or
       not decimal(v.user_id) or not decimal(v.version) or
       type(v.token_hash) ~= 'string' or v.token_hash == '' or
       type(v.refresh_expires_at) ~= 'number' then error('corrupt session record') end
    return v
end
local function same(a,b)
    return a.user_id == b.user_id and a.sid == b.sid and a.version == b.version
end
local function live(a)
    return a and version(prefix .. 'user_session_version:' .. a.user_id) == a.version
end
local function authkey(sid) return prefix .. 'auth_session:' .. sid end
local function refreshkey(hash) return prefix .. 'refresh_session:' .. hash end
local function deadline(v) return string.format('%.0f', v) end
local function put(key, value, expires)
    redis.call('SET', key, value, 'PXAT', deadline(expires))
end

if op == 'current' or op == 'all' then
    local v = version(KEYS[1])
    if not v then
        -- Candidate is cryptographically generated by Go for this call.
        redis.call('SET', KEYS[1], input.version)
        return input.version
    end
    if op == 'current' then return v end
    if v == '18446744073709551615' then return redis.error_reply('session version overflow') end
    local out = ''
    local carry = 1
    for i = #v, 1, -1 do
        local n = string.byte(v, i) - 48 + carry
        if n == 10 then n = 0; carry = 1 else carry = 0 end
        out = string.char(48 + n) .. out
    end
    if carry == 1 then out = '1' .. out end
    redis.call('SET', KEYS[1], out)
    return out
end

if op == 'access' then
    local a = read(KEYS[1])
    if not a or not same(a,input) or not live(a) then return 'invalid' end
    if type(a.access_valid_until) ~= 'number' then error('corrupt access deadline') end
    if a.access_valid_until <= now then return 'invalid' end
    return 'ok'
end

if op == 'create' then
    if version(KEYS[1]) ~= input.version then return 'version' end
    if input.refresh_expires_at <= now or input.access_valid_until <= now then return 'invalid' end
    if redis.call('EXISTS', KEYS[2], KEYS[3]) ~= 0 then return redis.error_reply('session key collision') end
    local encoded = cjson.encode(input)
    local until_time = math.max(input.refresh_expires_at, input.access_valid_until)
    put(KEYS[2], encoded, until_time)
    put(KEYS[3], encoded, input.refresh_expires_at)
    return 'ok'
end

local old = read(KEYS[1])
if not old or old.refresh_expires_at <= now then return 'invalid' end
local ak = authkey(old.sid)
local a = read(ak)
if not a or not same(a,old) or a.token_hash ~= input.old_hash or
   old.token_hash ~= input.old_hash or a.refresh_expires_at ~= old.refresh_expires_at or
   a.refresh_expires_at <= now or not live(a) then return 'invalid' end
if type(a.access_valid_until) ~= 'number' then error('corrupt access deadline') end
if op == 'find' then return cjson.encode(old) end
if not same(a,input) then return 'invalid' end
if op == 'revoke' then
    redis.call('DEL', ak, KEYS[1])
    return 'ok'
end
if op ~= 'rotate' then return redis.error_reply('unknown session operation') end
if input.refresh_expires_at <= now or input.access_valid_until <= now or
   input.token_hash == input.old_hash then return 'invalid' end
local rk = refreshkey(input.token_hash)
if redis.call('EXISTS', rk) ~= 0 then return 'invalid' end
input.old_hash = nil
input.access_valid_until = math.max(a.access_valid_until, input.access_valid_until)
local encoded = cjson.encode(input)
local until_time = math.max(input.refresh_expires_at, input.access_valid_until)
-- All checks, decoding and serialization precede the first mutation.
put(rk, encoded, input.refresh_expires_at)
put(ak, encoded, until_time)
redis.call('DEL', KEYS[1])
return 'ok'
